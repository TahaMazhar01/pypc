const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require('playwright-core')
module.exports = async function ({ base, email, password, runDir }) {
  assert.equal(new URL(base).hostname, '127.0.0.1')
  assert.ok(email.endsWith('@example.invalid'))
  const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true })
  const screenshots = [], checks = [], errors = []
  let stage = 'login'
  const pass = name => { checks.push(name); console.log('BROWSER PASS ' + name) }
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
    const page = await context.newPage()
    page.setDefaultTimeout(30000)
    page.on('pageerror', error => errors.push(error.name))
    await page.goto(base + '/login', { waitUntil: 'domcontentloaded', timeout: 120000 })
    await page.locator('form.auth-form[data-ready=true]').waitFor()
    await page.locator('#login-email').fill(email)
    await page.locator('#login-password').fill(password)
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await page.waitForURL(url => url.pathname === '/admin', { timeout: 60000, waitUntil: 'domcontentloaded' })
    async function visit(route) { stage = route; const response = await page.goto(base + route, { waitUntil: 'domcontentloaded', timeout: 120000 }); assert.equal(response.status(), 200); await page.locator('.admin-workspace[data-ready=true]').waitFor(); await page.evaluate(() => document.fonts.ready) }
    async function fit(label) {
      const size = await page.evaluate(() => ({ page: document.documentElement.scrollWidth, width: innerWidth }))
      assert.ok(size.page <= size.width + 1, label + ' page overflow')
      const modal = page.locator('dialog[open]')
      if (await modal.count()) assert.ok(await modal.evaluate(node => { const r = node.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth + 1 && r.top >= 0 && r.bottom <= innerHeight + 1 && node.scrollWidth <= node.clientWidth + 1 }), label + ' dialog overflow')
      pass(label + ' fits without page overflow')
    }
    async function capture(name, fullPage = false) { const file = path.join(runDir, name + '.png'); await page.screenshot({ path: file, fullPage, animations: 'disabled' }); screenshots.push(file) }
    const routes = ['/admin','/admin/users','/admin/roles','/admin/content','/admin/media','/admin/events','/admin/programmes','/admin/opportunities','/admin/applications','/admin/partnerships','/admin/visa-letters','/admin/messages','/admin/certificates','/admin/payments','/admin/emails','/admin/audit']
    for (const width of [1440,768,390]) {
      await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 })
      for (const route of routes) { await visit(route); await fit(width + 'px ' + route); if (route === '/admin') await capture('workspace-' + width, true) }
    }
    await visit('/admin/roles')
    const createRole = page.getByRole('button', { name: '+ Create custom role', exact: true })
    await createRole.click()
    const modal = page.getByRole('dialog')
    await modal.waitFor(); await fit('390px role dialog')
    await modal.getByLabel('Role name').fill('ADMIN')
    await modal.getByRole('button', { name: 'Save role', exact: true }).click()
    await modal.getByText('Built-in role names are reserved.', { exact: true }).waitFor()
    await fit('390px role validation error')
    for (let i = 0; i < 5; i++) { await page.keyboard.press('Tab'); assert.ok(await page.evaluate(() => Boolean(document.activeElement.closest('dialog')))) }
    await capture('workspace-role-dialog-mobile')
    await page.keyboard.press('Escape')
    await modal.waitFor({ state: 'hidden' })
    assert.ok(await createRole.evaluate(node => document.activeElement === node))
    pass('Modal keyboard focus is contained; Escape closes and restores focus')
    await createRole.click()
    const longName = 'Synthetic permissions ' + 'LongRoleName'.repeat(3)
    await modal.getByLabel('Role name').fill(longName)
    await modal.getByRole('button', { name: 'Save role', exact: true }).click()
    await modal.waitFor({ state: 'hidden' })
    await page.getByRole('button', { name: 'Edit ' + longName, exact: true }).click()
    await modal.getByLabel('Role name').fill('Synthetic browser revised role')
    await modal.getByRole('button', { name: 'Save role', exact: true }).click()
    await modal.waitFor({ state: 'hidden' })
    await page.getByRole('button', { name: 'Edit Synthetic browser revised role', exact: true }).click()
    page.once('dialog', dialog => dialog.accept())
    await modal.getByRole('button', { name: 'Delete role', exact: true }).click()
    await modal.waitFor({ state: 'hidden' })
    pass('Custom-role create/edit/delete works through mobile scrollable controls and confirmation')

    await visit('/admin/users?q=Updated%20member')
    await page.getByRole('button', { name: 'Edit member', exact: true }).click()
    await modal.getByLabel('Institution', { exact: true }).fill('Synthetic browser university ' + 'LongName'.repeat(10))
    await fit('390px member edit dialog with long data')
    await capture('workspace-member-dialog-mobile')
    await modal.getByRole('button', { name: 'Save member', exact: true }).click()
    await modal.waitFor({ state: 'hidden' })
    pass('Member profile changes save without access or password changes')

    await visit('/admin/messages')
    await capture('workspace-messages-mobile', true)
    await page.getByRole('button', { name: 'Review / update', exact: true }).first().click()
    await modal.getByLabel('Status', { exact: true }).selectOption('ARCHIVED')
    page.once('dialog', dialog => dialog.accept())
    await modal.getByRole('button', { name: 'Save decision', exact: true }).click()
    await modal.waitFor({ state: 'hidden' })
    await page.getByRole('button', { name: 'Review / update', exact: true }).first().click()
    await modal.getByRole('button', { name: 'Reopen for review', exact: true }).click()
    await modal.waitFor({ state: 'hidden' })
    pass('Message archive and reopen work through confirmed mobile review controls')

    await visit('/admin/certificates')
    await page.getByRole('button', { name: 'Edit certificate', exact: true }).first().click()
    await fit('390px certificate edit dialog')
    await modal.getByLabel('Certificate title').fill('Synthetic browser corrected certificate')
    await modal.getByRole('button', { name: 'Save certificate', exact: true }).click()
    await modal.waitFor({ state: 'hidden' })
    pass('Certificate correction saves through the admin dialog')

    await visit('/admin/payments')
    await page.getByRole('button', { name: 'Reconcile payment', exact: true }).click()
    await fit('390px reconciliation dialog')
    await modal.getByLabel('Decision', { exact: true }).selectOption('REJECT')
    await modal.getByLabel('Bank or receipt reference').fill('SYN-BROWSER-NOT-RECEIVED')
    page.once('dialog', dialog => dialog.accept())
    await modal.getByRole('button', { name: 'Record decision', exact: true }).click()
    await modal.waitFor({ state: 'hidden' })
    pass('Synthetic pending payment rejection requires evidence and confirmation')

    await visit('/admin/opportunities')
    await page.getByRole('button', { name: /Synthetic research position revised/ }).click()
    await fit('390px populated posting editor')
    page.once('dialog', dialog => dialog.accept())
    await page.getByRole('button', { name: 'Archive / unpublish', exact: true }).click()
    await page.getByRole('button', { name: 'Restore public version', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Restore public version', exact: true }).click()
    await page.getByRole('button', { name: 'Archive / unpublish', exact: true }).waitFor()
    await capture('workspace-posting-mobile', true)
    pass('Existing posting archive and restore work while keeping its saved record')
    await page.setViewportSize({ width: 768, height: 1024 })
    await fit('768px populated posting editor')
    await capture('workspace-posting-tablet', true)
    await visit('/admin/users?q=not-a-real-match')
    await page.getByText('No members match these filters.', { exact: true }).waitFor()
    await fit('Tablet empty member search')
    pass('Empty-state guidance renders without layout overflow')
    assert.deepEqual(errors, [])
    pass('No browser runtime errors across all admin modules')
    await page.evaluate(() => fetch('/api/auth/logout', { method: 'POST' }))
    return { browser: 'Microsoft Edge', version: browser.version(), checks, passed: checks.length, screenshots, syntheticOnly: true, completedAt: new Date().toISOString() }
  } catch (error) { throw new Error('Admin browser check failed at ' + stage + ' (' + error.name + '). ' + (error.stack?.split('\n').find(line => line.includes('check-admin-workspace-browser.cjs:'))?.trim() ?? '')) }
  finally { await browser.close() }
}
